-- 作品資料模型：works 表（電影／影集／Podcast 單集）+ episodes.work_id 綁定
-- issue_no 為作品特輯期號序號（頁面以國字呈現「第〇一四二號」）

create table if not exists works (
  id uuid primary key default gen_random_uuid(),
  kind text not null,
  title text not null,
  original_title text,
  year integer,
  region text,
  credit text,
  poster_url text,
  tmdb_id integer,
  podcast_show text,
  episode_number integer,
  synopsis text,
  slug text not null unique,
  issue_no integer generated by default as identity unique,
  created_at timestamptz not null default now(),
  constraint works_kind_check
    check (kind in ('movie', 'series', 'podcast_episode')),
  constraint works_slug_format
    check (slug ~ '^[a-z0-9][a-z0-9-]{0,63}$'),
  constraint works_year_range
    check (year is null or (year between 1880 and 2100)),
  constraint works_episode_number_positive
    check (episode_number is null or episode_number > 0)
);

alter table episodes
  add column if not exists work_id uuid references works(id) on delete set null;

create index if not exists idx_episodes_work_id
  on episodes(work_id)
  where work_id is not null;
